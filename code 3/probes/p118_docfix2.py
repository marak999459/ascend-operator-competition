    io.open(path, "w", encoding="utf-8").write(s)
    print("%s: %d edits, %d -> %d B (%+d)" % (path.split('/')[-1], len(edits), n0,
                                              len(s.encode("utf-8")), len(s.encode("utf-8")) - n0))


