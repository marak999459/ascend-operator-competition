def read(p):
    with io.open(p, encoding='utf-8') as fh:
        return fh.read()


def write(p, s):
    with io.open(p, 'w', encoding='utf-8') as fh:
        fh.write(s)


def sub(path, old, new, n=1, tag=''):
    s = read(path)
    c = s.count(old)
    assert c == n, 'sub %s: 期望 %d 处，实得 %d' % (tag or old[:30], n, c)
    write(path, s.replace(old, new))
    STATS.append([tag or old[:30], len(new) - len(old)])


def subline(path, key, new, tag=''):
    s = read(path)
    lines = s.split('\n')
    hits = [i for i, ln in enumerate(lines) if key in ln]
    assert len(hits) == 1, 'subline %s: 命中 %d 行' % (tag or key[:30], len(hits))
    i = hits[0]
    assert lines[i].startswith('|'), 'subline %s: 命中的不是表格行' % tag
    STATS.append([tag or key[:30], len(new) - len(lines[i])])
    lines[i] = new
    write(path, '\n'.join(lines))


