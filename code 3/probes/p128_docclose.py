def read(p):
    with io.open(p, encoding='utf-8') as fh:
        return fh.read()


def write(p, s):
    with io.open(p, 'w', encoding='utf-8') as fh:
        fh.write(s)


def fill(t):
    for k, v in VARS.items():
        t = t.replace(k, v)
    return t


def bl(t):
    return len(t.encode('utf-8'))


def sub(path, old, new, n=1, tag=''):
    old, new = fill(old), fill(new)
    s = read(path)
    c = s.count(old)
    assert c == n, 'sub %s: 期望 %d 处，实得 %d' % (tag or old[:30], n, c)
    if not DRY:
        write(path, s.replace(old, new))
    STATS.append([tag or old[:30], bl(new) - bl(old)])


def subline(path, prefix, new, tag=''):
    """整行替换：按"行首唯一前缀"定位（表格行改长句时用这个，避免手抄整行）。"""
    new = fill(new)
    s = read(path)
    lines = s.split('\n')
    hits = [i for i, ln in enumerate(lines) if ln.startswith(prefix)]
    assert len(hits) == 1, 'subline %s: 命中 %d 行' % (tag or prefix[:30], len(hits))
    i = hits[0]
    STATS.append([tag or prefix[:30], bl(new) - bl(lines[i])])
    lines[i] = new
    if not DRY:
        write(path, '\n'.join(lines))


def insafter(path, prefix, new, tag=''):
    """在"行首唯一前缀"那一行后面插一行（表格追加条目用，避免多行锚点的转义坑）。"""
    new = fill(new)
    s = read(path)
    lines = s.split('\n')
    hits = [i for i, ln in enumerate(lines) if ln.startswith(prefix)]
    assert len(hits) == 1, 'insafter %s: 命中 %d 行' % (tag or prefix[:30], len(hits))
    lines.insert(hits[0] + 1, new)
    STATS.append([tag or prefix[:30], bl(new) + new.count('\n') + 1])
    if not DRY:
        write(path, '\n'.join(lines))


def delline(path, prefix, tag=''):
    s = read(path)
    lines = s.split('\n')
    hits = [i for i, ln in enumerate(lines) if ln.startswith(prefix)]
    assert len(hits) == 1, 'delline %s: 命中 %d 行' % (tag or prefix[:30], len(hits))
    STATS.append([tag or prefix[:30], -bl(lines[hits[0]]) - 1])
    if not DRY:
        del lines[hits[0]]
        write(path, '\n'.join(lines))


